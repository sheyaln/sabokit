HEADER = """---
# AUTO-GENERATED by scripts/gen_apps_yml.py. Do not edit by hand.
# Adding a bundle: append to BUNDLES in the generator, then re-run it.
#
# Deploy every enabled app. Apps assume the bootstrap roles are already on
# the host (Docker, Traefik, scw-secrets). Each app's role asserts its
# prereqs at the top of tasks/main.yml — failures here mean bootstrap was
# skipped or something got removed.
#
# Each import is conditional on `enabled_apps.<key>` being non-null. That
# map is produced by `terraform output -json enabled_apps` in the per-env
# deploy.sh and passed via `-e @enabled_apps.json`. Apps the consumer
# didn't enable evaluate to null and the import is skipped.
#
# Vars are spelled out per app — Ansible's `import_playbook` requires a
# static dict, so we explicitly map each terraform-rendered var into the
# role namespace.
"""

DOWN_HEADER = """---
# AUTO-GENERATED by scripts/gen_apps_yml.py. Do not edit by hand.
# Adding a bundle: append to BUNDLES in the generator, then re-run it.
#
# Per-app teardown. One play per bundle, tagged [down, <app-slug>]. Stops
# and removes the app's compose stack via community.docker.docker_compose_v2
# (state: absent). Volumes are PRESERVED by default — the module's
# remove_volumes defaults to false. The sabokit CLI's --purge flag is
# responsible for volume removal.
#
# Each play loads the role defaults (for <slug>_install_dir etc.) via
# include_role with tasks_from=defaults, then runs compose-down. If a role
# ships its own tasks/down.yml, add an import_role line in this generator's
# render_down_bundle() — by convention, custom down hooks live there.
#
# Usage:
#   ansible-playbook down.yml -i env/inventory.ini -e @env/enabled_apps.json
#   ansible-playbook down.yml -i env/inventory.ini -e @env/enabled_apps.json --tags outline
"""


def extract_ansible_vars(outputs_tf: Path) -> list[str]:
    """Return the list of var names declared inside the `vars = { ... }`
    block of `output "ansible" { ... }` in the given outputs.tf."""
    text = outputs_tf.read_text()

    # Find the `output "ansible"` stanza first to avoid matching `vars = {`
    # inside other outputs (defensive — no app currently has that).
    m_output = re.search(
        r'output\s+"ansible"\s*\{(.*?)\n\}',
        text,
        flags=re.DOTALL,
    )
    if not m_output:
        return []
    stanza = m_output.group(1)

    # Find `vars = { ... }` within the stanza. Greedy until matching `}`
    # at the same indent.
    m_vars = re.search(
        r'vars\s*=\s*\{(.*?)\n\s*\}',
        stanza,
        flags=re.DOTALL,
    )
    if not m_vars:
        return []

    var_block = m_vars.group(1)

    # Each var line looks like "      foo_bar = ..." — capture the LHS.
    names = re.findall(
        r'^\s+([a-z][a-z0-9_]*)\s*=',
        var_block,
        flags=re.MULTILINE,
    )
    # Preserve order, drop duplicates if any (shouldn't be).
    seen: set[str] = set()
    ordered: list[str] = []
    for n in names:
        if n not in seen:
            seen.add(n)
            ordered.append(n)
    return ordered


def render_bundle(dir_name: str, consumer_key: str, role_slug: str,
                  vars: list[str], tier: str = "apps") -> str:
    """Render one import_playbook YAML block."""
    lines: list[str] = []
    lines.append(f"- import_playbook: ../{tier}/{dir_name}/ansible/playbook.yml")
    lines.append("  vars:")
    lines.append(
        f'    {role_slug}_host_group: '
        f'"{{{{ enabled_apps.{consumer_key}.ansible_group }}}}"'
    )
    for v in vars:
        lines.append(
            f'    {v}: '
            f'"{{{{ enabled_apps.{consumer_key}.ansible_vars.{v} }}}}"'
        )
    lines.append(
        f"  when: enabled_apps.{consumer_key} is defined "
        f"and enabled_apps.{consumer_key} is not none"
    )
    # Tier-tag mirrors the directory layout so consumers can scope by tier
    # (--tags operations, --tags application) without re-listing bundles.
    lines.append(f"  tags: [{tier}, {consumer_key}]")
    return "\n".join(lines) + "\n"


def render_multi_instance_bundle(dir_name: str, consumer_key: str) -> str:
    """Render the import_playbook for a multi-instance bundle. The playbook
    iterates internally over <key>.instances; we pass the whole map in."""
    lines: list[str] = []
    lines.append(f"- import_playbook: ../application/{dir_name}/ansible/playbook.yml")
    lines.append("  vars:")
    lines.append(
        f"    {consumer_key}_all_instances: "
        f'"{{{{ enabled_apps.{consumer_key}.instances }}}}"'
    )
    lines.append(
        f"  when: enabled_apps.{consumer_key} is defined"
    )
    lines.append(
        f"        and enabled_apps.{consumer_key}.instances is defined"
    )
    lines.append(
        f"        and (enabled_apps.{consumer_key}.instances | length) > 0"
    )
    lines.append(f"  tags: [application, {consumer_key}]")
    return "\n".join(lines) + "\n"


def render_down_multi_instance_bundle(dir_name: str, consumer_key: str) -> str:
    """Teardown for a multi-instance bundle. Iterates over instances and runs
    compose-down per install_dir. Volumes preserved."""
    lines: list[str] = []
    lines.append(f'- name: "down: {dir_name}"')
    lines.append("  hosts: all")
    lines.append("  become: true")
    lines.append("  gather_facts: false")
    lines.append(f"  tags: [down, {consumer_key}]")
    lines.append("  tasks:")
    lines.append(f"    - name: Stop and remove each {dir_name} instance")
    lines.append("      community.docker.docker_compose_v2:")
    lines.append(f'        project_src: "/opt/{dir_name}-{{{{ inst.key }}}}"')
    lines.append("        state: absent")
    lines.append(
        f"      loop: \"{{{{ (enabled_apps.{consumer_key} | default({{}}))"
        ".instances | default({}) | dict2items | "
        "selectattr('value.ansible_group', 'in', group_names) | list }}\""
    )
    lines.append("      loop_control:")
    lines.append("        loop_var: inst")
    lines.append('        label: "{{ inst.key }}"')
    lines.append("      ignore_errors: true  # compose file may already be gone")
    lines.append(
        f"      when: enabled_apps.{consumer_key} is defined"
    )
    lines.append(
        f"            and enabled_apps.{consumer_key}.instances is defined"
    )
    return "\n".join(lines) + "\n"


def render_down_bundle(dir_name: str, consumer_key: str,
                       role_slug: str, tier: str = "apps") -> str:
    """Render one teardown play. Targets `all` and scopes via tags + a
    per-task `when:` so the play parses even when an app isn't enabled.
    Loads role defaults so <slug>_install_dir is resolvable, then runs
    compose-down. Volumes preserved by default."""
    lines: list[str] = []
    lines.append(f'- name: "down: {dir_name}"')
    lines.append(
        f'  hosts: "{{{{ (enabled_apps.{consumer_key} | default({{}})).ansible_group '
        f"| default('all') }}}}\""
    )
    lines.append("  become: true")
    lines.append("  gather_facts: false")
    lines.append(f"  tags: [down, {consumer_key}]")
    lines.append("  tasks:")
    lines.append("    - name: Load role defaults")
    lines.append("      ansible.builtin.include_vars:")
    # The role directory matches the bundle dir name (hyphenated for
    # privacy-policy / protonmail-bridge); the role_slug (underscored) is only
    # the var prefix, so it can't index the path.
    lines.append(
        f'        file: "../{tier}/{dir_name}/ansible/roles/{dir_name}/defaults/main.yml"'
    )
    lines.append(
        f"      when: enabled_apps.{consumer_key} is defined "
        f"and enabled_apps.{consumer_key} is not none"
    )
    lines.append("    - name: Stop and remove the compose stack")
    lines.append("      community.docker.docker_compose_v2:")
    lines.append(
        f'        project_src: "{{{{ {role_slug}_install_dir '
        f"| default('/opt/{dir_name}') }}}}\""
    )
    lines.append("        state: absent")
    lines.append(
        f"      when: enabled_apps.{consumer_key} is defined "
        f"and enabled_apps.{consumer_key} is not none"
    )
    lines.append("      ignore_errors: true  # compose file may already be gone")
    return "\n".join(lines) + "\n"


